/**
 * 路径文本的小原语（纯函数，可在自检里跑）。
 *
 * 为什么值得单独一处：全仓有五个地方要「从整条路径里取出最后一段」，
 * 每处都各写了一遍 `split(/[\\/]/).pop()`。**原语只管切分**——
 * 空串、尾分隔符、空输入这些边界的**策略留在调用点**：
 * 有的回退整条路径（`fileNameOf`）、有的回退中心主题名（标签页标题）、
 * 有的用兜底名（资源文件名）。把策略也塞进原语，才是真正的行为合并。
 */

/** 取路径的最后一段（不含目录）。没有分隔符时返回它自己；空串 / 尾分隔符返回空串。 */
export function baseNameOf(path: string): string {
  const parts = path.split(/[\\/]/)
  return parts[parts.length - 1] ?? ''
}
